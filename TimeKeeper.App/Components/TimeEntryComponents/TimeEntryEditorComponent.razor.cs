    /// <summary>
    /// Handles changes to the selected work item and updates the associated time entry accordingly.
    /// </summary>
    /// <remarks>
    ///  This method updates the currently loaded time entry to reference the new work item and 
    ///  notifies any subscribers of the change. It also updates the user interface to reflect 
    ///  the new work item details.
    /// </remarks>
    /// <param name="item">
    ///  The work item that has been selected or changed. Cannot be null.
    /// </param>
    private async Task WorkItemListComponent_OnWorkItemChanged(WorkItem item)
    {
        if (this.LoadedTimeEntry != null)
        {
            // update the bound time entry with the new work item this will trigger the UI to
            // update and show the new work item details. We also need to update the work item
            // id on the time entry so that when we save it, it will be associated with the
            // correct work item in the database.
            //
            this.LoadedTimeEntry.WorkItem   = item;
            this.LoadedTimeEntry.WorkItemId = item.Id;

            // If the StartWork of the TimeEntry is undefined then let's set it to a default value.
            // The EndWork property is ok to be left NULL as the user may be creating a new active
            // TimeEntry. 
            // 
            this.LoadedTimeEntry.StartWork ??= DateTime.Now;

            // Notify the subscriber that the Loaded TimeEntry has changed (but those changes are 
            // temporary until saved to the datastore.
            //
            if (this.LoadedTimeEntryChanged.HasDelegate)
            {
                await this.LoadedTimeEntryChanged.InvokeAsync(this.LoadedTimeEntry);
            }
        }

        base.StateHasChanged();
    }

