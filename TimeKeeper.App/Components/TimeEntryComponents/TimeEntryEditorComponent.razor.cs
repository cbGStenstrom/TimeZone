    /// <summary>
    ///  Creates a new time entry for the currently loaded user and time entry context.
    /// </summary>
    /// <remarks>
    ///  If no time entry is loaded or no user is logged in, the operation will not create a new time
    ///  entry and returns <see langword="false"/>. On success, updates the loaded time entry with 
    ///  the newly created entry, including any new identifiers assigned by the data store.
    /// </remarks>
    /// <returns>
    ///  A task that represents the asynchronous operation. The task result is <see langword="true"/> 
    ///  if the time entry was successfully created; otherwise, <see langword="false"/>.
    /// </returns>
    private async Task<bool> CreateNewTimeEntry()
    {
        // If the LoadedTimeEntry or User are null then we cannot create a new time entry. 
        //
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("A time entry must be loaded to create a new time entry.");
        Laborer user              = this.EnsureUserIsLoaded("A user must be logged in to create a new time entry.");

        // initialize the return value to false. We will set it to true if we successfully create a
        // new time entry.
        //
        bool result          = false;
        TimeEntry? timeEntry = await base.TimeEntrySvc.CreateNewTimeEntry(loadedTimeEntry, user);

        // If the time entry was successfully created, update the LoadedTimeEntry with the new time entry
        // that was returned from the service. This will update the UI with any new information such as the
        // new time entry id that was generated by the database. We also set the result to true to indicate
        // that the time entry was successfully created.
        //
        if (timeEntry != null)
        {
            this.LoadedTimeEntry = timeEntry;
            this.LoadedTimeEntry.TakeSnapshot();
            result = true;
        }

        return result;
    }

    /// <summary>
    ///  Attempts to delete the currently loaded time entry for the logged-in user.
    /// </summary>
    /// <remarks>
    ///  This method requires that a time entry is loaded and a user is logged in before it can
    ///  perform the deletion. If either is not available, the operation will not proceed.
    /// </remarks>
    /// <returns>
    ///  A task that represents the asynchronous operation. The task result is <see langword="true"/> 
    ///  if the time entry was successfully deleted; otherwise, <see langword="false"/>.
    /// </returns>
    private async Task<bool> DeleteTimeEntry()
    {
        // If the LoadedTimeEntry or User are null then we cannot delete the time entry. 
        //
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("A time entry must be loaded to update an existing time entry.");
        Laborer user = this.EnsureUserIsLoaded("A user must be logged in to update an existing time entry.");

        // Initialize the return value to false. We will set it to true if we successfully delete
        // the Time Entry
        //
        bool result = await base.TimeEntrySvc.DeleteTimeEntry(loadedTimeEntry, user.Username);
        return result;
    }

    /// <summary>
    ///  Saves the specified time entry by creating a new record or updating an existing one, and 
    ///  notifies subscribers of the change.
    /// </summary>
    /// <remarks>
    ///  This method raises the LoadedTimeEntryChanged event after saving, allowing subscribers to
    ///  refresh related data or UI. If the time entry is new, a new record is created; otherwise, 
    ///  the existing record is updated.
    /// </remarks>
    /// <param name="timeEntry">
    ///  The time entry to save. Cannot be null and must be valid.
    /// </param>
    /// <returns>
    ///  A task that represents the asynchronous save operation.
    /// </returns>
    /// <exception cref="Exception">
    ///  Thrown if the time entry is not valid.
    /// </exception>
    private async Task SaveTimeEntry(TimeEntry timeEntry)
    {
        // Perform some validation on the time entry before we attempt to save it. If the time entry
        // is not valid, throw an exception.
        //
        ArgumentNullException.ThrowIfNull(timeEntry, nameof(timeEntry));
        bool isValid = timeEntry?.IsValid() ?? false;
        if (!isValid) throw new Exception("Invalid Time Entry");

        // If this is a NEW time entry then run the routine to create a new TimeEntry record.
        //
        if (this.IsNewTimeEntry)
        {
            await this.CreateNewTimeEntry();
        }

        // Otherwise, update the existing TimeEntry record.
        //
        else
        {
            await this.UpdateTimeEntry();
        }

        // Fire event handler to notify any subscribers that the time entry has been updated. This
        // will allow the parent component to refresh any data or UI that is bound to the time entry.
        //
        await LoadedTimeEntryChanged.InvokeAsync(timeEntry);

    }

    /// <summary>
    ///  Attempts to update the currently loaded time entry with the latest information for the 
    ///  logged-in user.
    /// </summary>
    /// <remarks>
    ///  This method requires that both a time entry is loaded and a user is logged in. If either 
    ///  is not available, the update operation will not proceed and the method returns false. 
    ///  Upon a successful update, the loaded time entry is refreshed with the persisted data, 
    ///  ensuring the UI reflects the latest state.
    /// </remarks>
    /// <returns>
    ///  true if the time entry was successfully updated; otherwise, false.
    /// </returns>
    private async Task<bool> UpdateTimeEntry()
    {
        // If the LoadedTimeEntry or User are null then we cannot update an existing time entry. 
        //
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("A time entry must be loaded to update an existing time entry.");
        Laborer user              = this.EnsureUserIsLoaded("A user must be logged in to update an existing time entry.");
        
        // initialize the return value to false. We will set it to true if we successfully create a
        // new time entry.
        //
        bool result          = false;
        TimeEntry? timeEntry = await base.TimeEntrySvc.UpdateTimeEntry(loadedTimeEntry, user);

        // If the time entry was successfully saved, update the LoadedTimeEntry with the persisted
        // time entry that was returned from the service. This will update the UI with any new
        // information. We also set the result to true to indicate that the time entry was successfully
        // updated.
        //
        if (timeEntry != null)
        {
            this.LoadedTimeEntry = timeEntry;
            this.LoadedTimeEntry.TakeSnapshot();
            result = true;
        }

        return result;
    }

