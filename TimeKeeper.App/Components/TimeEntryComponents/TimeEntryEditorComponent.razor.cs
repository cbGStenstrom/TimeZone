    ///  The loaded time entry.
    /// </returns>
    /// <exception cref="ArgumentException">
    ///  Thrown if no time entry is loaded.
    /// </exception>
    private TimeEntry EnsureTimeEntryIsLoaded(string errMsg)
    {
        if (this.LoadedTimeEntry == null) throw new ArgumentException(errMsg);
        else return this.LoadedTimeEntry;
    }

    /// <summary>
    ///  Ensures that a user is loaded in the current session and returns the user.
    /// </summary>
    /// <param name="errMsg">
    ///  The error message to include in the exception if no user is loaded. Cannot be null.
    /// </param>
    /// <returns>
    ///  The current user associated with the session.
    /// </returns>
    /// <exception cref="ArgumentException">
    ///  Thrown if no user is loaded in the session.
    /// </exception>
    private Laborer EnsureUserIsLoaded(string errMsg)
    {
        if (base.SessionService?.User == null) throw new ArgumentException(errMsg);
        else return base.SessionService.User;
    }

    /// <summary>
    ///  Finalizes the end work timestamp for the current time entry if it has not already been set.
    /// </summary>
    /// <remarks>
    ///  If the end work timestamp is already set, this method leaves it unchanged. Otherwise, it sets
    ///  the end work timestamp to the current system time.
    /// </remarks>
    /// <returns>
    ///  The updated time entry with the end work timestamp populated if it was previously unset.
    /// </returns>
    private TimeEntry FinalizeTimeEntry()
    {
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("");
        
        // If the End Work Timestamp is not populated then populate it with the current time.
        //
        if(!loadedTimeEntry.EndWork.HasValue)
        {
            loadedTimeEntry.EndWork = DateTime.Now;
        }

        return loadedTimeEntry;
    }

