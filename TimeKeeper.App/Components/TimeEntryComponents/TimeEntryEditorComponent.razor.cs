    /// <summary>
    ///  Handles the cancel action for the time entry dialog, deleting the current time entry and 
    ///  closing the dialog.
    /// </summary>
    /// <remarks>
    ///  This method deletes the loaded time entry, resets the loaded entry state, closes the dialog,
    ///  and triggers the save event. Use this method to cancel and remove the current time entry 
    ///  from the dialog.
    /// </remarks>
    /// <returns>
    ///  A task that represents the asynchronous operation.
    /// </returns>
    private async Task OnDiscardTimeEntryClick()
    {
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("");
        _ = await this.DeleteTimeEntry();

        this.LoadedTimeEntry = null;
        base.DialogSvc.Close();
        await this.OnSaveClicked.InvokeAsync();
    }

    /// <summary>
    ///  Handles the save operation for a time entry and optionally submits the associated work item 
    ///  for review based on the selected button item.
    /// </summary>
    /// <remarks>
    ///  If the editor is displayed in a dialog, the dialog is closed after saving. When the user
    ///  selects the submit option, the associated work item's review status is updated and persisted.
    /// </remarks>
    /// <param name="item">
    ///  The split button item that was clicked, determining whether to perform a standard save or 
    ///  submit the work item for review. If the item's Value is "submit", the work item is submitted 
    ///  for review.
    /// </param>
    /// <returns>
    ///  A task that represents the asynchronous operation.
    /// </returns>
    private async Task OnSaveClick(RadzenSplitButtonItem item)
    {
        // If item argument is null then it defaults to a "Save"
        // 
        string action = item == null ? "save" : item.Value.ToLower();

        // If the save request is to end the TimeEntry without a PR then process the TimeEntry to
        // make sure that an appropriate EndWork timestamp has been applied. Otherwise retrieve a
        // reference to the LoadedTimeEntry.
        //
        TimeEntry loadedTimeEntry = (action == "stopwork") ? this.FinalizeTimeEntry() : 
                                                             this.EnsureTimeEntryIsLoaded("");

        // Save the TimeEntry record
        //
        await this.SaveTimeEntry(loadedTimeEntry);

        // If the user clicked on the "Submit for Review" Button update the WorkItem status
        //
        if(item != null && item.Value == "submit")
        {
            // call to submit the WorkItem PR
            //
            if (loadedTimeEntry.WorkItem != null)
            {
                loadedTimeEntry.WorkItem.IsInReview = true;
                await base.WorkItemSvc.UpdateWorkItem(loadedTimeEntry.WorkItem);
            }
        }

        // If the Editor is being displayed in a Dialog box. Close it after saving
        //
        if(this.ShowDialogButtons) base.DialogSvc.Close();

        // Notify subscribers that the Save button was clicked.
        //
        await this.OnSaveClicked.InvokeAsync();
    }

    /// <summary>
    ///  Handles the save action for a new time entry, persists the entry, closes the dialog if open, 
    ///  and notifies subscribers.
    /// </summary>
    /// <returns>
    ///  A task that represents the asynchronous operation.
    /// </returns>
    private async Task OnSaveNewClick()
    {
        TimeEntry loadedTimeEntry = this.EnsureTimeEntryIsLoaded("");

        // Save the TimeEntry record
        //
        await this.SaveTimeEntry(loadedTimeEntry);

        // If the Editor is being displayed in a Dialog box. Close it after saving
        //
        if (this.ShowDialogButtons) base.DialogSvc.Close();

        // Notify subscribers that the Save button was clicked.
        //
        await this.OnSaveClicked.InvokeAsync();
    }

